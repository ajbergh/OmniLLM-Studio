package video

const (
	ParityPixelateOpaqueFixtureName       = "parity-pixelate-opaque-v1"
	ParityPixelateDecodedVideoFixtureName = "parity-pixelate-decoded-video-v1"

	parityPixelateOpaqueCanvasWidth  = 512
	parityPixelateOpaqueCanvasHeight = 512
	parityPixelateDecodedCanvasWidth = 640
	parityPixelateDecodedCanvasHeight = 360
	parityPixelateFPS                = 30
	parityPixelateDurationMS         = int64(2000)
	parityPixelateRegionWidth        = 403
	parityPixelateRegionHeight       = 307
	parityPixelateRegionX            = 17
	parityPixelateRegionY            = -8
	parityPixelateBlockSize          = 20
)

// ParityFixtureRegionFrame binds exact structural-region policy to canonical
// output frame identity. It is shared by focused fixture emitters and the
// parity-report manifest without relying on mutable screenshot filenames.
type ParityFixtureRegionFrame struct {
	FrameIndex int64          `json:"frame_index"`
	Regions    []ParityRegion `json:"regions"`
}

// ParityPixelateOpaqueFixture isolates the first preview-pixelate-raster-v1
// consumer path from the larger torture fixture. A 1:1 opaque PNG backdrop
// avoids codec/color-conversion noise while the non-divisible 403x307 region
// exercises the same floor downsample grid used by the legacy FFmpeg renderer.
func ParityPixelateOpaqueFixture() (TimelineDocument, []ParityFixtureAsset) {
	return parityPixelateFixture(
		ParityPixelateOpaqueFixtureName,
		parityPixelateOpaqueCanvasWidth,
		parityPixelateOpaqueCanvasHeight,
		"asset-square",
		ParityFixtureAsset{ID: "asset-square", Kind: "image", Width: 512, Height: 512, DurationMS: parityPixelateDurationMS, Description: "opaque 512x512 deterministic PNG"},
		"Opaque pixelate source",
	)
}

// ParityPixelateDecodedVideoFixture keeps the same static pixelate semantics but
// replaces the lossless PNG control with the deterministic H.264/yuv420p source
// generated by video-parity-fixture. Matching the canvas to the source's
// 640x360 dimensions avoids an unrelated media-resize variable so retained
// differences isolate browser/FFmpeg decode and RGB color-conversion behavior.
func ParityPixelateDecodedVideoFixture() (TimelineDocument, []ParityFixtureAsset) {
	return parityPixelateFixture(
		ParityPixelateDecodedVideoFixtureName,
		parityPixelateDecodedCanvasWidth,
		parityPixelateDecodedCanvasHeight,
		"asset-landscape",
		ParityFixtureAsset{ID: "asset-landscape", Kind: "video", Width: 640, Height: 360, DurationMS: 24000, Description: "deterministic H.264 yuv420p testsrc2 landscape video with stereo tone"},
		"Decoded H.264 pixelate source",
	)
}

func parityPixelateFixture(name string, canvasWidth, canvasHeight int, assetID string, sourceAsset ParityFixtureAsset, sourceTrackName string) (TimelineDocument, []ParityFixtureAsset) {
	doc := NewEmptyTimeline(canvasWidth, canvasHeight, parityPixelateFPS)
	doc.DurationMS = parityPixelateDurationMS
	doc.Canvas.Background = "#000000"
	doc.Metadata = map[string]any{"fixture": name}

	mediaZ := 1
	pixelateZ := 20
	doc.Tracks = []TimelineTrack{
		{
			ID:      "track-pixelate-source",
			Type:    TrackTypeLayer,
			Name:    sourceTrackName,
			Visible: true,
			Clips: []TimelineClip{{
				ID:           "clip-pixelate-source",
				AssetID:      assetID,
				StartMS:      0,
				DurationMS:   parityPixelateDurationMS,
				TrimOutMS:    parityPixelateDurationMS,
				PlaybackRate: 1,
				ZIndex:       &mediaZ,
				Transform: map[string]any{
					"x": 0.0, "y": 0.0, "z": 0.0,
					"scale": 1.0, "rotation": 0.0, "opacity": 1.0,
				},
				Effects:   []TimelineEffect{},
				Keyframes: []TimelineKeyframe{},
			}},
		},
		{
			ID:      "track-pixelate-region",
			Type:    TrackTypeShape,
			Name:    "Exact opaque pixelate region",
			Visible: true,
			Clips: []TimelineClip{{
				ID:         "clip-pixelate-region",
				StartMS:    0,
				DurationMS: parityPixelateDurationMS,
				TrimOutMS:  parityPixelateDurationMS,
				ZIndex:     &pixelateZ,
				Transform: map[string]any{
					"x": float64(parityPixelateRegionX),
					"y": float64(parityPixelateRegionY),
					"z": 0.0, "scale": 1.0, "rotation": 0.0, "opacity": 1.0,
				},
				Shape: &TimelineShape{
					Kind:       ShapeKindPixelate,
					Width:      parityPixelateRegionWidth,
					Height:     parityPixelateRegionHeight,
					BlurRadius: parityPixelateBlockSize,
				},
				Effects:   []TimelineEffect{},
				Keyframes: []TimelineKeyframe{},
			}},
		},
		{
			ID:      "track-pixelate-audio",
			Type:    TrackTypeAudio,
			Name:    "Capture harness audio",
			Visible: true,
			Clips: []TimelineClip{{
				ID:           "clip-pixelate-audio",
				AssetID:      "asset-audio",
				StartMS:      0,
				DurationMS:   parityPixelateDurationMS,
				TrimOutMS:    parityPixelateDurationMS,
				PlaybackRate: 1,
				Effects:      []TimelineEffect{},
				Keyframes:    []TimelineKeyframe{},
			}},
		},
	}

	assets := []ParityFixtureAsset{
		sourceAsset,
		{ID: "asset-audio", Kind: "audio", DurationMS: parityPixelateDurationMS, Description: "deterministic mono swept tone and impulses"},
	}
	return doc, assets
}

// ParityPixelateOpaqueFrameSamples keeps the lossless control fixture small and
// deterministic while sampling the start, two interior frames, and final frame.
func ParityPixelateOpaqueFrameSamples() []ParityFrameSample {
	return parityPixelateFrameSamples("pixelate")
}

// ParityPixelateDecodedVideoFrameSamples binds the same canonical output-frame
// identities while making the changing codec-decoded source explicit in names.
func ParityPixelateDecodedVideoFrameSamples() []ParityFrameSample {
	return parityPixelateFrameSamples("pixelate-video")
}

func parityPixelateFrameSamples(prefix string) []ParityFrameSample {
	return []ParityFrameSample{
		{Name: prefix + "-start", FrameIndex: 0, TimeMS: 0, Reason: "pixelate region start"},
		{Name: prefix + "-quarter", FrameIndex: 15, TimeMS: 500, Reason: "opaque pixelate interior"},
		{Name: prefix + "-half", FrameIndex: 30, TimeMS: 1000, Reason: "opaque pixelate interior"},
		{Name: prefix + "-final", FrameIndex: 59, TimeMS: 1967, Reason: "final active pixelate frame"},
	}
}

// ParityPixelateOpaqueRegionBounds mirrors the legacy renderer's integer
// center-relative region placement for the 512x512 lossless control fixture.
func ParityPixelateOpaqueRegionBounds() ParityBounds {
	return parityPixelateRegionBounds(parityPixelateOpaqueCanvasWidth, parityPixelateOpaqueCanvasHeight)
}

// ParityPixelateDecodedVideoRegionBounds mirrors the same placement semantics on
// the 640x360 decoded-video canvas without introducing source rescaling.
func ParityPixelateDecodedVideoRegionBounds() ParityBounds {
	return parityPixelateRegionBounds(parityPixelateDecodedCanvasWidth, parityPixelateDecodedCanvasHeight)
}

func parityPixelateRegionBounds(canvasWidth, canvasHeight int) ParityBounds {
	minX := (canvasWidth-parityPixelateRegionWidth)/2 + parityPixelateRegionX
	minY := (canvasHeight-parityPixelateRegionHeight)/2 + parityPixelateRegionY
	return ParityBounds{
		MinX: minX,
		MinY: minY,
		MaxX: minX + parityPixelateRegionWidth,
		MaxY: minY + parityPixelateRegionHeight,
	}
}

// ParityPixelateOpaqueRegionFrames requires an exact structural comparison of
// every sampled pixelate output rectangle for the lossless PNG control.
func ParityPixelateOpaqueRegionFrames(samples []ParityFrameSample) []ParityFixtureRegionFrame {
	return parityPixelateRegionFrames(samples, ParityPixelateOpaqueRegionBounds())
}

// ParityPixelateDecodedVideoRegionFrames binds the decoded-video measurement
// region to exact frame identity. The tolerant codec report consumes these
// bounds without weakening the lossless structural-exactness policy.
func ParityPixelateDecodedVideoRegionFrames(samples []ParityFrameSample) []ParityFixtureRegionFrame {
	return parityPixelateRegionFrames(samples, ParityPixelateDecodedVideoRegionBounds())
}

func parityPixelateRegionFrames(samples []ParityFrameSample, bounds ParityBounds) []ParityFixtureRegionFrame {
	frames := make([]ParityFixtureRegionFrame, 0, len(samples))
	for _, sample := range samples {
		frames = append(frames, ParityFixtureRegionFrame{
			FrameIndex: sample.FrameIndex,
			Regions: []ParityRegion{{
				Name:   "pixelate-output",
				Bounds: bounds,
			}},
		})
	}
	return frames
}
